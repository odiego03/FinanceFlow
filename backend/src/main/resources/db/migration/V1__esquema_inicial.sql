-- Esquema como estava quando o Flyway entrou (até então o Hibernate criava as tabelas com ddl-auto=update).
-- Num banco que já existe (o Neon compartilhado) esta migração não roda: o Flyway marca ela como baseline.
-- Num banco vazio ela cria tudo do zero.

create table usuarios (
    id          bigint generated by default as identity primary key,
    nome        varchar(255) not null,
    email       varchar(255) not null unique,
    senha_hash  varchar(255) not null,
    criado_em   timestamp(6) not null
);

create table categorias (
    id          bigint generated by default as identity primary key,
    usuario_id  bigint       not null references usuarios,
    nome        varchar(255) not null,
    tipo        varchar(255) not null check (tipo in ('RECEITA', 'DESPESA')),
    icone       varchar(255),
    cor         varchar(255),
    essencial   boolean
);

create table metas_financeiras (
    id           bigint generated by default as identity primary key,
    usuario_id   bigint        not null references usuarios,
    categoria_id bigint        not null references categorias,
    nome         varchar(255)  not null,
    valor_alvo   numeric(10,2) not null,
    data_alvo    date,
    criado_em    timestamp(6)  not null
);

create table parcelamentos (
    id                    bigint generated by default as identity primary key,
    usuario_id            bigint        not null references usuarios,
    categoria_id          bigint        not null references categorias,
    descricao             varchar(255)  not null,
    valor_total           numeric(10,2) not null,
    quantidade_parcelas   integer       not null,
    data_primeira_parcela date          not null,
    criado_em             timestamp(6)  not null
);

create table transacoes (
    id                    bigint generated by default as identity primary key,
    usuario_id            bigint        not null references usuarios,
    categoria_id          bigint        not null references categorias,
    tipo                  varchar(255)  not null check (tipo in ('RECEITA', 'DESPESA')),
    valor                 numeric(10,2) not null,
    descricao             varchar(255),
    data                  date          not null,
    criado_em             timestamp(6)  not null,
    identificador_externo varchar(255),
    parcelamento_id       bigint references parcelamentos,
    numero_parcela        integer
);

create table contribuicoes_meta (
    id            bigint generated by default as identity primary key,
    meta_id       bigint        not null references metas_financeiras,
    transacao_id  bigint        not null references transacoes,
    valor         numeric(10,2) not null,
    criado_em     timestamp(6)  not null
);

create table regras_categorizacao (
    id                     bigint generated by default as identity primary key,
    usuario_id             bigint       not null references usuarios,
    categoria_id           bigint       not null references categorias,
    descricao_normalizada  varchar(255) not null,
    unique (usuario_id, descricao_normalizada)
);

create table preferencias_usuarios (
    id                        bigint generated by default as identity primary key,
    usuario_id                bigint       not null unique references usuarios,
    ocultar_valores           boolean      not null,
    limite_essencial          numeric(5,2) not null,
    limite_total              numeric(5,2) not null,
    simulador_percentual_cdi  numeric(5,2) not null,
    simulador_prazo_meses     integer      not null,
    tema                      varchar(255) check (tema in ('CLARO', 'ESCURO', 'SISTEMA'))
);
