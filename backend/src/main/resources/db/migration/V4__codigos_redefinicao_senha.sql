-- Código de 6 dígitos mandado por e-mail no "esqueci minha senha". Guarda só o hash (BCrypt), nunca o código
create table codigos_redefinicao_senha (
    id          bigint generated by default as identity primary key,
    usuario_id  bigint       not null references usuarios,
    codigo_hash varchar(100) not null,
    expira_em   timestamp(6) not null,
    tentativas  integer      not null default 0,
    criado_em   timestamp(6) not null
);

create index if not exists idx_codigos_redefinicao_usuario on codigos_redefinicao_senha (usuario_id);
