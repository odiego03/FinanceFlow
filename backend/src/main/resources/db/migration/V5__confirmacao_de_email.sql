-- Conta nova só entra depois de confirmar o e-mail. As contas que já existem antes desta migração ficam como
-- confirmadas, senão todo mundo seria trancado pra fora
alter table usuarios add column email_verificado boolean not null default false;
update usuarios set email_verificado = true;

-- Link de confirmação mandado por e-mail. Guarda só o hash SHA-256 do token (como o link é longo e aleatório,
-- não precisa de BCrypt), nunca o token em si
create table tokens_verificacao_email (
    id         bigint generated by default as identity primary key,
    usuario_id bigint       not null references usuarios,
    token_hash varchar(64)  not null unique,
    expira_em  timestamp(6) not null,
    criado_em  timestamp(6) not null
);

create index if not exists idx_tokens_verificacao_usuario on tokens_verificacao_email (usuario_id);
